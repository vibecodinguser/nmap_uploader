/**
 * Очередь записи заметок.
 *
 * Каждая операция читает манифест, пишет шард и пишет манифест заново. Две
 * такие операции, запущенные одновременно (частая правка в панели или создание
 * сразу после правки), пишут один и тот же файл — Яндекс.Диск отвечает
 * `423 LOCKED`, потому что ресурс занят другой записью.
 *
 * Поэтому все изменения идут строго по одному. Чтения (`loadRemoteSnapshot`)
 * в очередь не попадают: они не конфликтуют между собой.
 */
let writeChain: Promise<unknown> = Promise.resolve()

/** Выполняет операцию записи, дожидаясь завершения предыдущей. */
export const enqueueNotesWrite = <T>(task: () => Promise<T>): Promise<T> => {
  const next = writeChain.then(task, task)
  // Ошибка одной операции не должна ломать очередь для следующих.
  writeChain = next.catch(() => {})
  return next
}

/** Дождаться, пока завершатся все поставленные в очередь записи. */
export const whenNotesWritesIdle = (): Promise<void> => writeChain.then(() => {})
